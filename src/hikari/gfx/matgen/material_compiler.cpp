std::string socket_hlsl_type(SocketType type) {
    switch (type) {
        case SocketType::Float: return "float";
        case SocketType::Float2: return "float2";
        case SocketType::Float3: return "float3";
        case SocketType::Float4: return "float4";
        case SocketType::Color: return "float4";
        case SocketType::Int: return "int";
        case SocketType::Bool: return "bool";
        case SocketType::Closure: return "float4";
    }
    return "float";
}

std::string var_name(uint32_t node_id, uint32_t sock_id) {
    return "var_n" + std::to_string(node_id) + "_s" + std::to_string(sock_id);
}

std::string format_float(float val) {
    std::ostringstream ss;
    ss << std::fixed << std::setprecision(4) << val << "f";
    return ss.str();
}

std::string format_socket_literal(const NodeSocket& sock) {
    switch (sock.type) {
        case SocketType::Float: {
            float v = std::holds_alternative<float>(sock.current_value) ? std::get<float>(sock.current_value) : 0.0f;
            return format_float(v);
        }
        case SocketType::Float2: {
            auto arr = std::holds_alternative<std::array<float, 2>>(sock.current_value) ? std::get<std::array<float, 2>>(sock.current_value) : std::array<float, 2>{0.0f, 0.0f};
            return "float2(" + format_float(arr[0]) + ", " + format_float(arr[1]) + ")";
        }
        case SocketType::Float3: {
            auto arr = std::holds_alternative<std::array<float, 3>>(sock.current_value) ? std::get<std::array<float, 3>>(sock.current_value) : std::array<float, 3>{0.0f, 0.0f, 0.0f};
            return "float3(" + format_float(arr[0]) + ", " + format_float(arr[1]) + ", " + format_float(arr[2]) + ")";
        }
        case SocketType::Float4:
        case SocketType::Color: {
            auto arr = std::holds_alternative<std::array<float, 4>>(sock.current_value) ? std::get<std::array<float, 4>>(sock.current_value) : std::array<float, 4>{1.0f, 1.0f, 1.0f, 1.0f};
            return "float4(" + format_float(arr[0]) + ", " + format_float(arr[1]) + ", " + format_float(arr[2]) + ", " + format_float(arr[3]) + ")";
        }
        case SocketType::Int: {
            int32_t v = std::holds_alternative<int32_t>(sock.current_value) ? std::get<int32_t>(sock.current_value) : 0;
            return std::to_string(v);
        }
        case SocketType::Bool: {
            bool b = std::holds_alternative<bool>(sock.current_value) ? std::get<bool>(sock.current_value) : false;
            return b ? "true" : "false";
        }
        case SocketType::Closure:
            return "float4(1.0f, 1.0f, 1.0f, 1.0f)";
    }
    return "0.0f";
}

std::string get_input_expr(const MaterialGraph& graph, const MaterialNode& node, std::string_view sock_name) {
    for (const auto& sock : node.inputs) {
        if (sock.name == sock_name) {
            if (sock.connected_link_id >= 0) {
                const NodeLink* link = graph.find_link(static_cast<uint32_t>(sock.connected_link_id));
                if (link) {
                    return var_name(link->from_node_id, link->from_socket_id);
                }
            }
            return format_socket_literal(sock);
        }
    }
    return "0.0f";
}

