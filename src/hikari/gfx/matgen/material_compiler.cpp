CompiledMaterialShader MaterialCompiler::compile(const MaterialGraph& graph) {
    CompiledMaterialShader shader;
    shader.cache_hash = graph.compute_graph_hash();

    std::vector<uint32_t> sorted = graph.topological_sort();
    shader.hlsl_source = emit_hlsl(graph, sorted, shader.uniforms, shader.texture_slots);

    // Calculate uniform buffer byte alignment
    uint32_t current_offset = 0;
    for (auto& u : shader.uniforms) {
        u.byte_offset = current_offset;
        current_offset += u.byte_size;
    }
    // 16-byte alignment round up
    shader.cbuffer_size_bytes = (current_offset + 15) & ~15;

    return shader;
}

std::string MaterialCompiler::emit_hlsl(const MaterialGraph& graph,
                                        const std::vector<uint32_t>& sorted_nodes,
                                        std::vector<UniformProperty>& out_uniforms,
                                        std::vector<std::string>& out_textures) {
    (void)out_uniforms;
    (void)out_textures;
    std::ostringstream ss;

    ss << "// Auto-generated by Hikari Material Compiler (matgen)\n";
    ss << "// Graph Hash: 0x" << std::hex << graph.compute_graph_hash() << std::dec << "\n\n";

    ss << "struct MaterialSurface {\n";
    ss << "    float3 base_color;\n";
    ss << "    float roughness;\n";
    ss << "    float metallic;\n";
    ss << "    float3 specular_f0;\n";
    ss << "    float3 normal_world;\n";
    ss << "    float3 emissive;\n";
    ss << "    float alpha;\n";
    ss << "    int shading_model;\n";
    ss << "};\n\n";

    ss << "void EvaluateMaterialSurface(in VSOut input, out MaterialSurface surface) {\n";
    ss << "    surface.base_color = float3(1.0f, 1.0f, 1.0f);\n";
    ss << "    surface.roughness = 0.5f;\n";
    ss << "    surface.metallic = 0.0f;\n";
    ss << "    surface.specular_f0 = float3(0.04f, 0.04f, 0.04f);\n";
    ss << "    surface.normal_world = normalize(input.normal_world);\n";
    ss << "    surface.emissive = float3(0.0f, 0.0f, 0.0f);\n";
    ss << "    surface.alpha = 1.0f;\n";
    ss << "    surface.shading_model = 0;\n\n";

    for (uint32_t nid : sorted_nodes) {
        const MaterialNode* node = graph.find_node(nid);
        if (!node) continue;

        ss << "    // Node: " << node->title << " (ID " << node->id << ")\n";

        switch (node->type) {
            case NodeType::TexCoord: {
                for (const auto& out : node->outputs) {
                    if (out.name == "UV") {
                        ss << "    float2 " << var_name(node->id, out.id) << " = input.uv;\n";
                    } else if (out.name == "Normal") {
                        ss << "    float3 " << var_name(node->id, out.id) << " = normalize(input.normal_world);\n";
                    } else if (out.name == "Position") {
                        ss << "    float3 " << var_name(node->id, out.id) << " = input.pos_world;\n";
                    }
                }
                break;
            }
            case NodeType::NoiseTexture: {
                std::string vec = get_input_expr(graph, *node, "Vector");
                std::string scale = get_input_expr(graph, *node, "Scale");
                std::string detail = get_input_expr(graph, *node, "Detail");
                std::string roughness = get_input_expr(graph, *node, "Roughness");
                std::string lacunarity = get_input_expr(graph, *node, "Lacunarity");

                for (const auto& out : node->outputs) {
                    if (out.name == "Fac") {
                        ss << "    float " << var_name(node->id, out.id) << " = FractalNoise3D("
                           << vec << ", " << scale << ", " << detail << ", " << roughness << ", " << lacunarity << ");\n";
                    } else if (out.name == "Color") {
                        ss << "    float4 " << var_name(node->id, out.id) << " = float4("
                           << "FractalNoise3D(" << vec << ", " << scale << ", " << detail << ", " << roughness << ", " << lacunarity << ").xxx, 1.0f);\n";
                    }
                }
                break;
            }
            case NodeType::VoronoiTexture: {
                std::string vec = get_input_expr(graph, *node, "Vector");
                std::string scale = get_input_expr(graph, *node, "Scale");
                std::string rand = get_input_expr(graph, *node, "Randomness");
                std::string smooth = get_input_expr(graph, *node, "Smoothness");

                std::string res_var = "voronoi_res_" + std::to_string(node->id);
                ss << "    VoronoiResult " << res_var << " = Voronoi3D(" << vec << ", " << scale << ", " << rand << ", " << smooth << ");\n";
                for (const auto& out : node->outputs) {
                    if (out.name == "Distance") {
                        ss << "    float " << var_name(node->id, out.id) << " = " << res_var << ".distance_f1;\n";
                    } else if (out.name == "Color") {
                        ss << "    float4 " << var_name(node->id, out.id) << " = float4(" << res_var << ".cell_color, 1.0f);\n";
                    }
                }
                break;
            }
            case NodeType::Mix: {
                std::string fac = get_input_expr(graph, *node, "Fac");
                std::string a = get_input_expr(graph, *node, "A");
                std::string b = get_input_expr(graph, *node, "B");
                for (const auto& out : node->outputs) {
                    ss << "    float4 " << var_name(node->id, out.id) << " = lerp(" << a << ", " << b << ", saturate(" << fac << "));\n";
                }
                break;
            }
            case NodeType::MathScalar: {
                std::string a = get_input_expr(graph, *node, "A");
                std::string b = get_input_expr(graph, *node, "B");
                for (const auto& out : node->outputs) {
                    ss << "    float " << var_name(node->id, out.id) << " = " << a << " + " << b << ";\n";
                }
                break;
            }
            case NodeType::VectorMath: {
                std::string a = get_input_expr(graph, *node, "A");
                std::string b = get_input_expr(graph, *node, "B");
                for (const auto& out : node->outputs) {
                    if (out.name == "Vector") {
                        ss << "    float3 " << var_name(node->id, out.id) << " = " << a << " + " << b << ";\n";
                    } else if (out.name == "Value") {
                        ss << "    float " << var_name(node->id, out.id) << " = length(" << a << ");\n";
                    }
                }
                break;
            }
            case NodeType::BumpMap: {
                std::string height = get_input_expr(graph, *node, "Height");
                std::string strength = get_input_expr(graph, *node, "Strength");
                std::string dist = get_input_expr(graph, *node, "Distance");
                for (const auto& out : node->outputs) {
                    ss << "    float3 " << var_name(node->id, out.id) << " = PerturbNormalFromHeight(input.pos_world, input.normal_world, "
                       << height << ", " << strength << ", " << dist << ");\n";
                }
                break;
            }
            case NodeType::PrincipledBSDF: {
                std::string base = get_input_expr(graph, *node, "Base Color");
                std::string metallic = get_input_expr(graph, *node, "Metallic");
                std::string roughness = get_input_expr(graph, *node, "Roughness");
                std::string specular = get_input_expr(graph, *node, "Specular");
                std::string emission = get_input_expr(graph, *node, "Emission");
                std::string normal = get_input_expr(graph, *node, "Normal");
                std::string alpha = get_input_expr(graph, *node, "Alpha");

                for (const auto& out : node->outputs) {
                    ss << "    surface.base_color = (" << base << ").rgb;\n";
                    ss << "    surface.metallic = " << metallic << ";\n";
                    ss << "    surface.roughness = " << roughness << ";\n";
                    ss << "    surface.specular_f0 = float3(0.08f * (" << specular << "), 0.08f * (" << specular << "), 0.08f * (" << specular << "));\n";
                    ss << "    surface.emissive = (" << emission << ").rgb;\n";
                    ss << "    surface.normal_world = " << normal << ";\n";
                    ss << "    surface.alpha = " << alpha << ";\n";
                    ss << "    surface.shading_model = 0;\n";
                    ss << "    float4 " << var_name(node->id, out.id) << " = float4(surface.base_color, surface.alpha);\n";
                }
                break;
            }
            case NodeType::ToonBSDF: {
                std::string col = get_input_expr(graph, *node, "Color");
                std::string normal = get_input_expr(graph, *node, "Normal");
                std::string thresh = get_input_expr(graph, *node, "Threshold");
                for (const auto& out : node->outputs) {
                    ss << "    surface.base_color = (" << col << ").rgb;\n";
                    ss << "    surface.normal_world = " << normal << ";\n";
                    ss << "    surface.shading_model = 8;\n"; // Cel
                    ss << "    float4 " << var_name(node->id, out.id) << " = " << col << ";\n";
                }
                break;
            }
            case NodeType::MaterialOutput: {
                std::string alpha = get_input_expr(graph, *node, "Alpha");
                ss << "    surface.alpha = " << alpha << ";\n";
                break;
            }
            default:
                break;
        }
        ss << "\n";
    }

    ss << "}\n";
    return ss.str();
}

